package stylus

import (
	"bytes"
	"testing"
)

func TestAddressFromString(t *testing.T) {
	b := AddressFromString("0x6221a9c005f6e47eb398fd867784cacfdcfff4e7")
	c :=  []byte{0x62,0x21,0xa9,0xc0,0x05,0xf6,0xe4,0x7e,0xb3,0x98,0xfd,0x86,0x77,0x84,0xca,0xcf,0xdc,0xff,0xf4,0xe7,}
	if !bytes.Equal(c, b.Bytes()) {
		t.Fatalf("comp not equal: was %x", b)
	}
}
